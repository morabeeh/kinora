fn main() -> ExitCode {
    let process_start = Instant::now();
    match run(process_start) {
        Ok(code) => code,
        Err(err) => {
            tracing::error!("Kinora stopped: {err:#}");
            write_line(true, &format!("kinora: {err:#}"));
            ExitCode::FAILURE
        }
    }
}

fn run(process_start: Instant) -> anyhow::Result<ExitCode> {
    let args = match cli::parse(std::env::args_os().skip(1)) {
        Ok(args) => args,
        Err(message) => {
            write_line(
                true,
                &format!(
                    "kinora: {message}

{}",
                    cli::USAGE
                ),
            );
            return Ok(ExitCode::from(2));
        }
    };
    let text = match args.action {
        cli::Action::Run => None,
        cli::Action::Help => Some(cli::USAGE.to_owned()),
        cli::Action::Version => Some(format!("Kinora {}", env!("CARGO_PKG_VERSION"))),
    };
    if let Some(text) = text {
        write_line(false, &text);
        return Ok(ExitCode::SUCCESS);
    }

    let paths = kinora_platform::paths::app_paths();
    let _log_guard = logging::init(paths.as_ref().map(|p| p.log_dir.as_path()))?;
    tracing::info!(version = env!("CARGO_PKG_VERSION"), "starting Kinora");
    let mut store = settings_store::SettingsStore::load(paths.map(|p| p.settings_file()));

    let files: Vec<PathBuf> = args
        .files
        .iter()
        .map(|file| std::path::absolute(file).unwrap_or_else(|_| file.clone()))
        .collect();

    // Single instance: give the file to the running Kinora and quit (brief §5.1).
    let mut primary = None;
    if store.settings.general.single_instance && !args.new_window && !args.bench_startup {
        match single_instance::start(&files) {
            Ok(Startup::Forwarded) => {
                tracing::info!("handed the file to the running Kinora");
                return Ok(ExitCode::SUCCESS);
            }
            Ok(Startup::Primary(server)) => primary = Some(server),
            Err(err) => tracing::warn!(%err, "single-instance mode unavailable"),
        }
    }

    let (plan, lite, budgets) = hardware_profile(&args, &store.settings);

    #[cfg(feature = "heif")]
    kinora_decode::set_heif_availability_check(|| {
        // Windows delay-loads heif.dll; elsewhere libheif is linked normally.
        kinora_platform::library_available("heif.dll")
    });

    startup::select_backend(&plan)?;
    let window = ui::AppWindow::new().context("could not create the main window")?;
    ui::Theme::get(&window).set_lite(lite);

    let screen_guess = store
        .settings
        .detected
        .screen_size
        .map_or(Size::new(1920, 1080), |[w, h]| Size::new(w, h));
    let viewer = viewer::Viewer::new(
        &window,
        viewer::Config {
            budgets,
            settings: store.settings.clone(),
            screen_guess,
            bench: args.bench_startup,
            process_start,
        },
    )?;
    viewer::Viewer::bind(&window);
    viewer::install(Rc::clone(&viewer));
    install_file_drop(&window);

    if let Some(server) = primary {
        let weak = window.as_weak();
        server.serve(move |request| {
            let weak = weak.clone();
            let _ = slint::invoke_from_event_loop(move || {
                viewer::with_viewer(|v| v.open_paths(&request.paths));
                if let Some(window) = weak.upgrade() {
                    bring_to_front(&window);
                }
            });
        })?;
    }

    // Start decoding the opened file before the window even appears.
    if let Some(file) = files.first() {
        viewer.open(file);
    }
    window.show().context("could not show the window")?;
    tracing::info!(
        ms = process_start.elapsed().as_millis(),
        "window shown (from process start)"
    );
    let gl_renderer = watch_gl_renderer(&window);

    slint::run_event_loop().context("the UI event loop failed")?;
    let _ = window.hide();

    remember_session(&mut store, viewer.screen_size(), gl_renderer.as_ref());
    viewer::uninstall();
    drop(viewer);
    store.save();
    tracing::info!("Kinora exited normally");
    Ok(ExitCode::SUCCESS)
}

/// Facts learned this session, saved for the next start.
fn remember_session(
    store: &mut settings_store::SettingsStore,
    screen: Size,
    gl_renderer: Option<&Rc<RefCell<Option<String>>>>,
) {
    let detected = &mut store.settings.detected;
    detected.screen_size = Some([screen.width, screen.height]);
    detected.app_version = Some(String::from(env!("CARGO_PKG_VERSION")));
    if let Some(name) = gl_renderer.and_then(|found| found.borrow().clone()) {
        detected.software_gl = kinora_core::hardware::is_software_renderer_name(&name);
        detected.gl_renderer = Some(name);
    }
}

/// Hardware profile → tier, renderer, Lite mode and budgets (brief §7.6).
fn hardware_profile(
    args: &cli::Args,
    settings: &kinora_core::settings::Settings,
) -> (startup::RendererPlan, bool, kinora_core::hardware::Budgets) {
    let probe_started = Instant::now();
    let mut hardware = kinora_platform::hardware::probe();
    if std::env::var("KINORA_SIMULATE").is_ok_and(|v| v.eq_ignore_ascii_case("lite")) {
        tracing::warn!("KINORA_SIMULATE=lite: simulating a Lite-tier PC");
        hardware = hardware.simulate_lite();
    }
    let detected = &settings.detected;
    if cfg!(target_os = "linux")
        && hardware.gpu == Gpu::Unknown
        && detected.software_gl
        && detected.app_version.as_deref() == Some(env!("CARGO_PKG_VERSION"))
    {
        hardware.gpu = Gpu::SoftwareOnly(detected.gl_renderer.clone());
    }
    let tier = classify(&hardware);
    let plan =
        startup::choose_renderer(args.renderer, settings.performance.renderer, &hardware.gpu);
    let lite = startup::lite_mode(
        args.lite,
        settings.performance.lite_mode,
        tier,
        plan.software,
    );
    let budgets =
        kinora_core::hardware::budgets(&hardware, lite, settings.performance.image_cache_mb);
    tracing::info!(
        ?tier,
        cores = hardware.logical_cores,
        ram_mb = hardware.total_ram_bytes.unwrap_or(0) / (1024 * 1024),
        avx2 = hardware.avx2,
        gpu = ?hardware.gpu,
        lite,
        workers = budgets.decode_workers,
        cache_mb = budgets.image_cache_bytes / (1024 * 1024),
        probe_ms = probe_started.elapsed().as_millis(),
        "hardware profile"
    );
    (plan, lite, budgets)
}

/// Writes one line to stdout or stderr: the command line's only output (help, version,
/// usage errors), printed before logging starts.
fn write_line(to_stderr: bool, text: &str) {
    let line = format!(
        "{text}
"
    );
    // Nothing sensible to do if the console is gone.
    let _ = if to_stderr {
        std::io::stderr().lock().write_all(line.as_bytes())
    } else {
        std::io::stdout().lock().write_all(line.as_bytes())
    };
}

/// Files dropped on the window open like files given on the command line. Slint has no
/// file-drop event of its own, so this listens to winit's.
fn install_file_drop(window: &ui::AppWindow) {
    window
        .window()
        .on_winit_window_event(|_, event| match event {
            winit::event::WindowEvent::HoveredFile(_) => {
                viewer::with_viewer(|v| v.set_drop_hover(true));
                EventResult::Propagate
            }
            winit::event::WindowEvent::HoveredFileCancelled => {
                viewer::with_viewer(|v| v.set_drop_hover(false));
                EventResult::Propagate
            }
            winit::event::WindowEvent::DroppedFile(path) => {
                let path = path.clone();
                viewer::with_viewer(|v| {
                    v.set_drop_hover(false);
                    v.open(&path);
                });
                EventResult::Propagate
            }
            _ => EventResult::Propagate,
        });
}

/// Restores and focuses the window when another Kinora handed us a file.
fn bring_to_front(window: &ui::AppWindow) {
    window.window().with_winit_window(|winit_window| {
        winit_window.set_minimized(false);
        winit_window.focus_window();
    });
}

/// Linux: the OpenGL renderer name tells whether drawing really happens on a GPU. Mesa's
/// llvmpipe means "no GPU": it is remembered, so the next start uses the software renderer
/// and Lite mode right away (brief §7.6). The name arrives with the first frame.
fn watch_gl_renderer(window: &ui::AppWindow) -> Option<Rc<RefCell<Option<String>>>> {
    if !cfg!(target_os = "linux") {
        return None;
    }
    let found: Rc<RefCell<Option<String>>> = Rc::default();
    let sink = Rc::clone(&found);
    window
        .window()
        .set_rendering_notifier(move |state, api| {
            if sink.borrow().is_some() || !matches!(state, slint::RenderingState::RenderingSetup) {
                return;
            }
            if let slint::GraphicsAPI::NativeOpenGL { get_proc_address } = api {
                let name = kinora_platform::gl::renderer_name(get_proc_address);
                tracing::info!(gl_renderer = ?name, "OpenGL renderer");
                *sink.borrow_mut() = name;
            }
        })
        .ok()?; // not an OpenGL renderer (software or Skia): nothing to learn
    Some(found)
}
