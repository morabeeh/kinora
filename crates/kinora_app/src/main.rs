//! Kinora — a fast, private photo and video viewer.
//!
//! Application entry point (the Rust equivalent of `Program.cs`): reads the command line
//! and settings, hands the file to an already running Kinora if there is one, detects the
//! hardware, picks the renderer and Lite mode, then runs the viewer.

// In release builds on Windows, don't open a console window next to the app.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

