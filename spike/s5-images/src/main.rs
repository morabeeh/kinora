//! ⚠️ THROWAWAY spike S5–S7: image formats, EXIF orientation, HiDPI-correct 100%, and
//! CPU-viewport zoom/pan (the software-renderer path).
//!
//! Usage:
//!   `s5-images gen <dir>`    write the synthetic test images (needs `KINORA_FFMPEG`)
//!   `s5-images bench <dir>`  decode every file, check orientation, time scaled JPEG + viewport
//!   `s5-images view <dir>`   interactive viewer

