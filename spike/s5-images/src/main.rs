fn main() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")),
        )
        .with_writer(std::io::stderr)
        .with_target(false)
        .try_init()
        .map_err(|err| anyhow::anyhow!(err))?;
    let mut args = std::env::args().skip(1);
    let command = args
        .next()
        .context("usage: s5-images gen|bench|view <dir>")?;
    let dir = PathBuf::from(args.next().context("missing <dir>")?);
    match command.as_str() {
        "gen" => generate::generate(&dir),
        "bench" => bench(&dir),
        "view" => view(&dir),
        other => anyhow::bail!("unknown command `{other}`"),
    }
}

fn files(dir: &Path) -> anyhow::Result<Vec<PathBuf>> {
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.is_file())
        .collect();
    files.sort();
    Ok(files)
}

fn ms(duration: Duration) -> f64 {
    duration.as_secs_f64() * 1000.0
}

fn median(mut values: Vec<f64>) -> f64 {
    values.sort_by(f64::total_cmp);
    values.get(values.len() / 2).copied().unwrap_or(0.0)
}

fn bench(dir: &Path) -> anyhow::Result<()> {
    for path in files(dir)? {
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("?")
            .to_owned();
        let bytes = std::fs::read(&path)?;
        let mut times = Vec::new();
        let mut last = None;
        for _ in 0..3 {
            let started = Instant::now();
            let result = decode::decode(&bytes);
            times.push(ms(started.elapsed()));
            last = Some(result);
        }
        match last.context("no decode ran")? {
            Ok(img) => {
                let orientation = orientation_check(&name, &img);
                tracing::info!(
                    "DECODE {name:<28} {:<5?} {}×{} frames={} {:>7.1} ms {orientation}",
                    img.format,
                    img.width,
                    img.height,
                    img.frames,
                    median(times)
                );
            }
            Err(err) => tracing::info!("DECODE {name:<28} ERROR (handled): {err:#}"),
        }
    }
    bench_scaled_jpeg(dir)?;
    bench_viewport(dir)
}

/// For `orient-N.jpg`: the red square must end up in the corner EXIF orientation N implies.
fn orientation_check(name: &str, img: &decode::Decoded) -> String {
    let Some(tag) = name
        .strip_prefix("orient-")
        .and_then(|s| s.strip_suffix(".jpg"))
    else {
        return String::new();
    };
    let half = generate::MARK / 2;
    let (width, height) = (img.width, img.height);
    let (corner, px, py) = match tag {
        "1" | "5" => ("top-left", half, half),
        "2" | "6" => ("top-right", width - half, half),
        "3" | "7" => ("bottom-right", width - half, height - half),
        _ => ("bottom-left", half, height - half),
    };
    let index = usize::try_from(py).unwrap_or(0) * usize::try_from(width).unwrap_or(0)
        + usize::try_from(px).unwrap_or(0);
    let pixel = img.rgba.get(index * 4..index * 4 + 3).unwrap_or_default();
    let red = matches!(pixel, [r, g, b] if *r > 180 && *g < 90 && *b < 90);
    let swapped = matches!(tag, "5" | "6" | "7" | "8");
    let dims_ok = (width > height) != swapped;
    if red && dims_ok {
        format!("orientation OK (red at {corner})")
    } else {
        format!("orientation WRONG (expected red at {corner}, got {pixel:?}, {width}×{height})")
    }
}

fn bench_scaled_jpeg(dir: &Path) -> anyhow::Result<()> {
    let bytes = std::fs::read(dir.join("photo-24mp.jpg"))?;
    let mut full = Vec::new();
    for _ in 0..3 {
        let started = Instant::now();
        decode::decode(&bytes)?;
        full.push(ms(started.elapsed()));
    }
    tracing::info!(
        "SCALED 6000×4000 full decode (zune-jpeg via image) {:>7.1} ms",
        median(full)
    );
    for (w, h) in [
        (6000, 4000),
        (1920, 1080),
        (1366, 768),
        (960, 540),
        (480, 270),
    ] {
        let mut times = Vec::new();
        let mut size = (0, 0);
        for _ in 0..3 {
            let started = Instant::now();
            let (dw, dh, _) = decode::decode_jpeg_scaled(&bytes, w, h)?;
            times.push(ms(started.elapsed()));
            size = (dw, dh);
        }
        tracing::info!(
            "SCALED jpeg-decoder for {w}×{h} screen → decoded {}×{} in {:>7.1} ms",
            size.0,
            size.1,
            median(times)
        );
    }
    Ok(())
}

fn bench_viewport(dir: &Path) -> anyhow::Result<()> {
    let img = decode::decode(&std::fs::read(dir.join("photo-24mp.jpg"))?)?;
    let src = fr::images::Image::from_vec_u8(img.width, img.height, img.rgba, fr::PixelType::U8x4)?;
    let mut resizer = fr::Resizer::new();
    for window in [(1920, 1080), (1366, 768), (3840, 2160)] {
        for (label, zoom) in [
            ("fit", None),
            ("50%", Some(0.5)),
            ("100%", Some(1.0)),
            ("200%", Some(2.0)),
        ] {
            let mut times = Vec::new();
            for step in 0..30u32 {
                let offset = f64::from(step) * 37.0;
                let view = viewport::View {
                    zoom,
                    center: (2000.0 + offset, 1500.0 + offset / 2.0),
                };
                let plan = viewport::plan((img.width, img.height), window, &view);
                let started = Instant::now();
                viewport::render(&mut resizer, &src, &plan)?;
                times.push(ms(started.elapsed()));
            }
            times.sort_by(f64::total_cmp);
            let p95 = times.get(times.len() * 95 / 100).copied().unwrap_or(0.0);
            tracing::info!(
                "VIEWPORT 24 MP → {}×{} {label:<5} p50 {:>6.1} ms  p95 {:>6.1} ms",
                window.0,
                window.1,
                median(times.clone()),
                p95
            );
        }
    }
    Ok(())
}

struct ViewerState {
    files: Vec<PathBuf>,
    index: usize,
    source: Option<fr::images::Image<'static>>,
    image_size: (u32, u32),
    view: viewport::View,
    drag_origin: (f64, f64),
    resizer: fr::Resizer,
    decode_ms: f64,
    status: String,
}

fn view(dir: &Path) -> anyhow::Result<()> {
    let app = ui::Viewer::new()?;
    let state = Rc::new(RefCell::new(ViewerState {
        files: files(dir)?,
        index: 0,
        source: None,
        image_size: (1, 1),
        view: viewport::View {
            zoom: None,
            center: (0.0, 0.0),
        },
        drag_origin: (0.0, 0.0),
        resizer: fr::Resizer::new(),
        decode_ms: 0.0,
        status: String::new(),
    }));
    load_current(&mut state.borrow_mut());

    let refresh = {
        let weak = app.as_weak();
        let state = Rc::clone(&state);
        move || {
            if let Some(app) = weak.upgrade() {
                show(&app, &mut state.borrow_mut());
            }
        }
    };
    let refresh = Rc::new(refresh);

    let (s, r) = (Rc::clone(&state), Rc::clone(&refresh));
    app.on_navigate(move |delta| {
        {
            let mut st = s.borrow_mut();
            let count = st.files.len().max(1);
            st.index = if delta < 0 {
                (st.index + count - 1) % count
            } else {
                (st.index + 1) % count
            };
            load_current(&mut st);
        }
        r();
    });
    let (s, r) = (Rc::clone(&state), Rc::clone(&refresh));
    app.on_key(move |text| {
        {
            let mut st = s.borrow_mut();
            match text.as_str() {
                "1" => st.view.zoom = Some(1.0),
                "0" => st.view.zoom = None,
                _ => return,
            }
        }
        r();
    });
    let (s, r, weak) = (Rc::clone(&state), Rc::clone(&refresh), app.as_weak());
    app.on_wheel(move |notches, x, y| {
        if let Some(app) = weak.upgrade() {
            zoom_at_cursor(&app, &mut s.borrow_mut(), notches, (x, y));
            r();
        }
    });
    let s = Rc::clone(&state);
    app.on_drag_start(move || {
        let mut st = s.borrow_mut();
        st.drag_origin = st.view.center;
    });
    let (s, r, weak) = (Rc::clone(&state), Rc::clone(&refresh), app.as_weak());
    app.on_drag(move |dx, dy| {
        let Some(app) = weak.upgrade() else { return };
        let scale = f64::from(app.window().scale_factor());
        let size = app.window().size();
        {
            let mut st = s.borrow_mut();
            let zoom = viewport::plan(st.image_size, (size.width, size.height), &st.view).zoom;
            if st.view.zoom.is_none() {
                st.view.zoom = Some(zoom);
            }
            st.view.center = (
                st.drag_origin.0 - f64::from(dx) * scale / zoom,
                st.drag_origin.1 - f64::from(dy) * scale / zoom,
            );
        }
        r();
    });
    let r = Rc::clone(&refresh);
    app.on_resized(move || r());

    refresh();
    app.run()?;
    Ok(())
}

/// Zoom by one wheel notch, keeping the image point under the cursor where it is.
fn zoom_at_cursor(app: &ui::Viewer, st: &mut ViewerState, notches: f32, cursor: (f32, f32)) {
    let scale = f64::from(app.window().scale_factor());
    let size = app.window().size();
    let window = (size.width, size.height);
    let before = viewport::plan(st.image_size, window, &st.view);
    let factor = if notches > 0.0 { 1.25 } else { 0.8 };
    let zoom = (before.zoom * factor).clamp(0.02, 32.0);
    let offset_x = (f64::from(size.width) - f64::from(before.out_w)) / 2.0;
    let offset_y = (f64::from(size.height) - f64::from(before.out_h)) / 2.0;
    let cursor = (f64::from(cursor.0) * scale, f64::from(cursor.1) * scale);
    let under = (
        before.left + (cursor.0 - offset_x) / before.zoom,
        before.top + (cursor.1 - offset_y) / before.zoom,
    );
    let center_px = (f64::from(size.width) / 2.0, f64::from(size.height) / 2.0);
    st.view = viewport::View {
        zoom: Some(zoom),
        center: (
            under.0 - (cursor.0 - center_px.0) / zoom,
            under.1 - (cursor.1 - center_px.1) / zoom,
        ),
    };
}

fn load_current(st: &mut ViewerState) {
    let Some(path) = st.files.get(st.index).cloned() else {
        return;
    };
    let name = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("?")
        .to_owned();
    let started = Instant::now();
    let result = std::fs::read(&path)
        .map_err(anyhow::Error::from)
        .and_then(|bytes| decode::decode(&bytes));
    st.decode_ms = ms(started.elapsed());
    st.view = viewport::View {
        zoom: None,
        center: (0.0, 0.0),
    };
    match result.and_then(|img| {
        let size = (img.width, img.height);
        Ok((
            size,
            fr::images::Image::from_vec_u8(img.width, img.height, img.rgba, fr::PixelType::U8x4)?,
        ))
    }) {
        Ok((size, source)) => {
            st.image_size = size;
            st.view.center = (f64::from(size.0) / 2.0, f64::from(size.1) / 2.0);
            st.source = Some(source);
            st.status = format!(
                "{name}  {}×{}  decoded in {:.0} ms",
                size.0, size.1, st.decode_ms
            );
        }
        Err(err) => {
            st.source = None;
            st.status = format!("{name}  — can't open: {err:#}");
        }
    }
}

fn show(app: &ui::Viewer, st: &mut ViewerState) {
    let size = app.window().size();
    let scale = app.window().scale_factor();
    let Some(source) = st.source.as_ref() else {
        app.set_frame(slint::Image::default());
        app.set_info(st.status.clone().into());
        return;
    };
    let plan = viewport::plan(st.image_size, (size.width, size.height), &st.view);
    let started = Instant::now();
    match viewport::render(&mut st.resizer, source, &plan) {
        Ok(frame) => {
            let viewport_ms = ms(started.elapsed());
            let buffer = SharedPixelBuffer::<Rgba8Pixel>::clone_from_slice(
                frame.buffer(),
                plan.out_w,
                plan.out_h,
            );
            app.set_frame(slint::Image::from_rgba8(buffer));
            app.set_frame_px_width(i32::try_from(plan.out_w).unwrap_or(0));
            app.set_frame_px_height(i32::try_from(plan.out_h).unwrap_or(0));
            app.set_info(
                format!(
                    "{}  |  zoom {:.0}%  |  viewport {viewport_ms:.1} ms  |  scale {scale}",
                    st.status,
                    plan.zoom * 100.0
                )
                .into(),
            );
        }
        Err(err) => app.set_info(format!("{}  — viewport failed: {err:#}", st.status).into()),
    }
}
