//! ⚠️ THROWAWAY spike S1 — compare Slint renderers on this machine.
//!
//! Shows a generated 24 MP photo fitted into the window. Pick the renderer with
//! `SLINT_BACKEND=winit-<name>` (femtovg, femtovg-wgpu, skia, skia-opengl, skia-software, software).
//!
//! Options:
//!   `--auto-resize`   resize the window 60×/s (800×500 ↔ 1600×1000, 2 s cycle) to measure
//!                     how many frames the renderer actually delivers while resizing
//!   `--seconds N`     quit after N seconds and print a `RESULT` line

use std::cell::RefCell;
use std::rc::Rc;
use std::time::{Duration, Instant};

use anyhow::Context as _;
use slint::{ComponentHandle as _, PhysicalSize, Rgba8Pixel, SharedPixelBuffer, Timer, TimerMode};
use tracing_subscriber::EnvFilter;

mod ui {
    // Generated by Slint; same scoped allowance as kinora_app.
    #![allow(
        clippy::unwrap_used,
        clippy::as_conversions,
        clippy::panic,
        clippy::indexing_slicing,
        missing_debug_implementations
    )]
    slint::include_modules!();
}

const PHOTO_WIDTH: u32 = 6000;
const PHOTO_HEIGHT: u32 = 4000;

struct Options {
    auto_resize: bool,
    seconds: Option<u64>,
}

fn main() -> anyhow::Result<()> {
    let process_start = Instant::now();
    tracing_subscriber::fmt()
        .with_env_filter(EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")))
        .with_writer(std::io::stderr)
        .try_init()
        .map_err(|err| anyhow::anyhow!(err))?;

    let options = parse_options()?;
    let label = std::env::var("SLINT_BACKEND").unwrap_or_else(|_| String::from("default"));

    let started = Instant::now();
    let photo = make_photo(PHOTO_WIDTH, PHOTO_HEIGHT)?;
    tracing::info!(ms = started.elapsed().as_millis(), "generated 24 MP test photo");

    let window = ui::BenchWindow::new().context("could not create window")?;
    window.set_label(label.clone().into());
    window.set_photo(slint::Image::from_rgba8(photo));

    // Timestamp of every presented frame (if this renderer supports the notifier).
    let frames: Rc<RefCell<Vec<Instant>>> = Rc::default();
    let notifier_frames = Rc::clone(&frames);
    let notifier_ok = window
        .window()
        .set_rendering_notifier(move |state, _graphics_api| {
            if matches!(state, slint::RenderingState::AfterRendering) {
                notifier_frames.borrow_mut().push(Instant::now());
            }
        })
        .map_err(|err| tracing::warn!(?err, "no rendering notifier; use SLINT_DEBUG_PERFORMANCE"))
        .is_ok();

    let resize_timer = Timer::default();
    if options.auto_resize {
        let weak = window.as_weak();
        let resize_start = Instant::now();
        resize_timer.start(TimerMode::Repeated, Duration::from_millis(16), move || {
            if let Some(window) = weak.upgrade() {
                let (width, height) = triangle_size(resize_start.elapsed());
                window.window().set_size(PhysicalSize::new(width, height));
            }
        });
    }

    let quit_timer = Timer::default();
    if let Some(seconds) = options.seconds {
        quit_timer.start(TimerMode::SingleShot, Duration::from_secs(seconds), || {
            if let Err(err) = slint::quit_event_loop() {
                tracing::error!(?err, "could not quit event loop");
            }
        });
    }

    window.run().context("event loop failed")?;

    if notifier_ok {
        report(&label, process_start, &frames.borrow(), options.auto_resize);
    }
    Ok(())
}

fn parse_options() -> anyhow::Result<Options> {
    let mut options = Options { auto_resize: false, seconds: None };
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--auto-resize" => options.auto_resize = true,
            "--seconds" => {
                let value = args.next().context("--seconds needs a value")?;
                options.seconds = Some(value.parse().context("--seconds must be a number")?);
            }
            other => anyhow::bail!("unknown argument `{other}`"),
        }
    }
    Ok(options)
}

/// Window size on a 2-second triangle wave between 800×500 and 1600×1000 physical pixels.
fn triangle_size(elapsed: Duration) -> (u32, u32) {
    let phase = u32::try_from(elapsed.as_millis() % 2000).unwrap_or(0);
    let t = if phase < 1000 { phase } else { 2000 - phase };
    (800 + t * 800 / 1000, 500 + t * 500 / 1000)
}

/// A gradient with a fine 2-px checkerboard on top, so scaling quality and aliasing are visible.
fn make_photo(width: u32, height: u32) -> anyhow::Result<SharedPixelBuffer<Rgba8Pixel>> {
    let mut buffer = SharedPixelBuffer::<Rgba8Pixel>::new(width, height);
    let w = usize::try_from(width)?;
    let h = usize::try_from(height)?;
    for (index, pixel) in buffer.make_mut_slice().iter_mut().enumerate() {
        let (x, y) = (index % w, index / w);
        let checker = ((x / 2 + y / 2) % 2) * 55;
        let blocks = ((x / 300 + y / 300) % 2) * 120;
        *pixel = Rgba8Pixel {
            r: u8::try_from(x * 200 / w + checker).unwrap_or(u8::MAX),
            g: u8::try_from(y * 200 / h + checker).unwrap_or(u8::MAX),
            b: u8::try_from(blocks + checker).unwrap_or(u8::MAX),
            a: u8::MAX,
        };
    }
    Ok(buffer)
}

fn report(label: &str, process_start: Instant, frames: &[Instant], auto_resize: bool) {
    let (Some(first), Some(last)) = (frames.first(), frames.last()) else {
        tracing::warn!("no frames recorded");
        return;
    };
    let mut intervals: Vec<Duration> =
        frames.iter().zip(frames.iter().skip(1)).map(|(a, b)| b.duration_since(*a)).collect();
    intervals.sort_unstable();
    let percentile = |p: usize| {
        let index = (intervals.len().saturating_sub(1)) * p / 100;
        intervals.get(index).map_or(0.0, |d| d.as_secs_f64() * 1000.0)
    };
    let span = last.duration_since(*first).as_secs_f64();
    let count = f64::from(u32::try_from(frames.len()).unwrap_or(u32::MAX));
    let fps = if span > 0.0 { (count - 1.0) / span } else { 0.0 };
    let slow_frames = intervals.iter().filter(|d| d.as_millis() > 33).count();
    tracing::info!(
        "RESULT renderer={label} auto_resize={auto_resize} first_frame_ms={first_ms} frames={n} fps={fps:.1} \
         p50_ms={p50:.1} p95_ms={p95:.1} max_ms={max:.1} slow_frames_over_33ms={slow_frames}",
        first_ms = first.duration_since(process_start).as_millis(),
        n = frames.len(),
        p50 = percentile(50),
        p95 = percentile(95),
        max = percentile(100),
    );
}
