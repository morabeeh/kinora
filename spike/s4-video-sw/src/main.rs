//! ⚠️ THROWAWAY spike S4 — video backend C (last resort: no GPU and no native child window,
//! e.g. Wayland with llvmpipe).
//!
//! mpv's *software* render API draws each frame into a CPU buffer of at most 854×480
//! (`PROJECT_BRIEF.md` §7.6) on a dedicated render thread; the UI thread only receives finished
//! pixel buffers and shows them scaled to the window, with our control bar on top.
//!
//! Usage: `s4-video-sw <file> [--hwdec X] [--seconds N] [--opt name=value]...`

use std::ffi::{c_int, c_void};
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::mpsc::{self, Receiver, Sender};
use std::sync::{Arc, Mutex};
use std::thread::JoinHandle;
use std::time::{Duration, Instant};

use anyhow::Context as _;
use libmpv2::Mpv;
use libmpv2_sys as sys;
use slint::{ComponentHandle as _, Rgba8Pixel, SharedPixelBuffer, Timer, TimerMode};
use tracing_subscriber::EnvFilter;

mod ui {
    // Generated by Slint; same scoped allowance as kinora_app.
    #![allow(
        clippy::unwrap_used,
        clippy::as_conversions,
        clippy::panic,
        clippy::indexing_slicing,
        clippy::todo, // std-widgets generate `todo!("Components written in Rust can not get embedded yet.")`
        missing_debug_implementations
    )]
    slint::include_modules!();
}

/// Largest size mpv renders at in software mode (brief §7.6); Slint scales it up.
const MAX_WIDTH: u32 = 854;
const MAX_HEIGHT: u32 = 480;

struct Options {
    file: String,
    hwdec: String,
    seconds: Option<u64>,
    extra: Vec<(String, String)>,
}

#[derive(Default)]
struct Stats {
    load_started: Option<Instant>,
    first_frame: Option<Instant>,
    frames: Vec<Instant>,
    render_ms: Vec<f64>,
}

fn main() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")),
        )
        .with_writer(std::io::stderr)
        .try_init()
        .map_err(|err| anyhow::anyhow!(err))?;
    let options = parse_options()?;
    let backend = std::env::var("SLINT_BACKEND").unwrap_or_else(|_| String::from("default"));

    let app = ui::VideoWindow::new().context("could not create window")?;
    app.set_label(format!("{backend}  sw-render  hwdec={}", options.hwdec).into());

    let mpv = create_mpv(&options)?;
    // Throwaway spike: leak for a 'static borrow (the real wrapper will own it).
    let mpv: &'static Mpv = Box::leak(Box::new(mpv));
    let ctx = SwRenderContext::create(mpv)?;

    // mpv → render thread wake-ups; UI → render thread target size; shared stats.
    let (wake_tx, wake_rx) = mpsc::channel::<()>();
    ctx.set_update_callback(wake_tx.clone());
    let target = Arc::new(AtomicU64::new(pack(MAX_WIDTH, MAX_HEIGHT)));
    let stop = Arc::new(AtomicBool::new(false));
    let stats = Arc::new(Mutex::new(Stats::default()));
    let render_thread = spawn_render_thread(
        ctx,
        wake_rx,
        Arc::clone(&target),
        Arc::clone(&stop),
        app.as_weak(),
        Arc::clone(&stats),
    )?;

    if let Ok(mut stats) = stats.lock() {
        stats.load_started = Some(Instant::now());
    }
    mpv.command("loadfile", &[&options.file])
        .map_err(|err| anyhow::anyhow!("loadfile: {err:?}"))?;
    wire_controls(&app, mpv);

    // Keep the software render size matched to the window (capped at 854×480).
    let ui_timer = Timer::default();
    let weak = app.as_weak();
    ui_timer.start(TimerMode::Repeated, Duration::from_millis(100), move || {
        if let Some(app) = weak.upgrade() {
            let size = app.window().size();
            let (w, h) = fit(size.width, size.height);
            target.store(pack(w, h), Ordering::Relaxed);
            let pos = mpv.get_property::<f64>("time-pos").unwrap_or(0.0);
            let dur = mpv.get_property::<f64>("duration").unwrap_or(0.0);
            app.set_position_text(format!("{} / {}  ({w}×{h})", clock(pos), clock(dur)).into());
            app.set_paused(mpv.get_property::<bool>("pause").unwrap_or(false));
        }
    });

    let quit_timer = Timer::default();
    if let Some(seconds) = options.seconds {
        quit_timer.start(TimerMode::SingleShot, Duration::from_secs(seconds), || {
            if let Err(err) = slint::quit_event_loop() {
                tracing::error!(?err, "could not quit event loop");
            }
        });
    }

    app.run().context("event loop failed")?;
    stop.store(true, Ordering::Relaxed);
    if wake_tx.send(()).is_err() {
        tracing::warn!("render thread already gone");
    }
    if render_thread.join().is_err() {
        tracing::error!("render thread panicked");
    }
    if let Ok(stats) = stats.lock() {
        report(mpv, &backend, &options, &stats);
    }
    Ok(())
}

fn parse_options() -> anyhow::Result<Options> {
    let mut args = std::env::args().skip(1);
    let file = args.next().context("usage: s4-video-sw <file> [options]")?;
    let mut options = Options {
        file,
        hwdec: String::from("no"),
        seconds: None,
        extra: Vec::new(),
    };
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--hwdec" => options.hwdec = args.next().context("--hwdec needs a value")?,
            "--seconds" => {
                options.seconds = Some(args.next().context("--seconds needs a value")?.parse()?);
            }
            "--opt" => {
                let pair = args.next().context("--opt needs name=value")?;
                let (name, value) = pair.split_once('=').context("--opt needs name=value")?;
                options.extra.push((name.to_owned(), value.to_owned()));
            }
            other => anyhow::bail!("unknown argument `{other}`"),
        }
    }
    Ok(options)
}

fn create_mpv(options: &Options) -> anyhow::Result<Mpv> {
    Mpv::with_initializer(|init| {
        for (name, value) in [
            ("vo", "libmpv"),
            ("hwdec", options.hwdec.as_str()),
            ("config", "no"),
        ] {
            init.set_option(name, value)?;
        }
        for (name, value) in [
            ("ytdl", "no"),
            ("load-scripts", "no"),
            ("osc", "no"),
            ("input-default-bindings", "no"),
            ("terminal", "no"),
            ("video-timing-offset", "0"),
            ("sw-fast", "yes"), // fast software scaling (brief §7.6)
            ("keep-open", "yes"),
            ("loop-file", "inf"),
        ] {
            if let Err(err) = init.set_option(name, value) {
                tracing::warn!(name, ?err, "mpv option not accepted");
            }
        }
        for (name, value) in &options.extra {
            init.set_option(name, value.as_str())?;
        }
        Ok(())
    })
    .map_err(|err| anyhow::anyhow!("could not create mpv: {err:?}"))
}

/// mpv's software render context (raw FFI; libmpv2's safe wrapper only supports OpenGL).
struct SwRenderContext(*mut sys::mpv_render_context);

// SAFETY: mpv allows render-context calls from any thread as long as they are not concurrent.
// After creation, only the render thread touches the context (and frees it at the end).
unsafe impl Send for SwRenderContext {}

impl SwRenderContext {
    fn create(mpv: &'static Mpv) -> anyhow::Result<Self> {
        let mut params = [
            sys::mpv_render_param {
                type_: sys::mpv_render_param_type_MPV_RENDER_PARAM_API_TYPE,
                data: sys::MPV_RENDER_API_TYPE_SW.as_ptr().cast_mut().cast(),
            },
            sys::mpv_render_param {
                type_: 0,
                data: std::ptr::null_mut(),
            },
        ];
        let mut ctx = std::ptr::null_mut();
        // SAFETY: `params` is a valid array terminated by type 0, the API-type string is a
        // 'static NUL-terminated constant, and the mpv handle lives forever (leaked).
        let err = unsafe {
            sys::mpv_render_context_create(&raw mut ctx, mpv.ctx.as_ptr(), params.as_mut_ptr())
        };
        anyhow::ensure!(
            err >= 0 && !ctx.is_null(),
            "mpv_render_context_create failed: {err}"
        );
        Ok(Self(ctx))
    }

    /// mpv calls back (on its own thread) whenever a new frame may be ready.
    fn set_update_callback(&self, wake: Sender<()>) {
        unsafe extern "C" fn on_update(data: *mut c_void) {
            // SAFETY: `data` is the `Sender` leaked below; it is never freed.
            let wake = unsafe { &*data.cast::<Sender<()>>() };
            // A closed channel just means we are shutting down.
            let _ = wake.send(());
        }
        let data: *mut Sender<()> = Box::into_raw(Box::new(wake));
        // SAFETY: the context is valid; `data` stays valid forever (intentionally leaked).
        unsafe {
            sys::mpv_render_context_set_update_callback(self.0, Some(on_update), data.cast());
        }
    }

    fn has_new_frame(&self) -> bool {
        // SAFETY: valid context, called from the render thread only.
        let flags = unsafe { sys::mpv_render_context_update(self.0) };
        flags & u64::from(sys::mpv_render_update_flag_MPV_RENDER_UPDATE_FRAME) != 0
    }

    fn render(&self, buffer: &mut SharedPixelBuffer<Rgba8Pixel>) -> anyhow::Result<()> {
        let (width, height) = (buffer.width(), buffer.height());
        let mut size: [c_int; 2] = [c_int::try_from(width)?, c_int::try_from(height)?];
        let mut stride: usize = usize::try_from(width)? * 4;
        let format = c"rgb0";
        let pixels = buffer.make_mut_bytes();
        let mut params = [
            sys::mpv_render_param {
                type_: sys::mpv_render_param_type_MPV_RENDER_PARAM_SW_SIZE,
                data: size.as_mut_ptr().cast(),
            },
            sys::mpv_render_param {
                type_: sys::mpv_render_param_type_MPV_RENDER_PARAM_SW_FORMAT,
                data: format.as_ptr().cast_mut().cast(),
            },
            sys::mpv_render_param {
                type_: sys::mpv_render_param_type_MPV_RENDER_PARAM_SW_STRIDE,
                data: (&raw mut stride).cast(),
            },
            sys::mpv_render_param {
                type_: sys::mpv_render_param_type_MPV_RENDER_PARAM_SW_POINTER,
                data: pixels.as_mut_ptr().cast(),
            },
            sys::mpv_render_param {
                type_: 0,
                data: std::ptr::null_mut(),
            },
        ];
        // SAFETY: every pointer refers to a local that outlives the call; the pixel buffer
        // holds exactly stride × height bytes, as mpv requires.
        let err = unsafe { sys::mpv_render_context_render(self.0, params.as_mut_ptr()) };
        anyhow::ensure!(err >= 0, "mpv_render_context_render failed: {err}");
        // "rgb0": the 4th byte is undefined — make every pixel opaque.
        for pixel in buffer.make_mut_slice() {
            pixel.a = u8::MAX;
        }
        Ok(())
    }
}

impl Drop for SwRenderContext {
    fn drop(&mut self) {
        // SAFETY: freed exactly once, on the render thread that used it.
        unsafe { sys::mpv_render_context_free(self.0) };
    }
}

fn spawn_render_thread(
    ctx: SwRenderContext,
    wake: Receiver<()>,
    target: Arc<AtomicU64>,
    stop: Arc<AtomicBool>,
    window: slint::Weak<ui::VideoWindow>,
    stats: Arc<Mutex<Stats>>,
) -> anyhow::Result<JoinHandle<()>> {
    std::thread::Builder::new()
        .name(String::from("mpv-sw-render"))
        .spawn(move || {
            while wake.recv().is_ok() && !stop.load(Ordering::Relaxed) {
                while wake.try_recv().is_ok() {} // coalesce wake-ups
                if !ctx.has_new_frame() {
                    continue;
                }
                let (width, height) = unpack(target.load(Ordering::Relaxed));
                let mut buffer = SharedPixelBuffer::<Rgba8Pixel>::new(width, height);
                let started = Instant::now();
                if let Err(err) = ctx.render(&mut buffer) {
                    tracing::error!("software render failed: {err:#}");
                    continue;
                }
                let done = Instant::now();
                if let Ok(mut stats) = stats.lock() {
                    stats
                        .render_ms
                        .push(done.duration_since(started).as_secs_f64() * 1000.0);
                    stats.first_frame.get_or_insert(done);
                    stats.frames.push(done);
                }
                // Only the finished pixels cross to the UI thread (SharedPixelBuffer is Send).
                let shown = window.upgrade_in_event_loop(move |app| {
                    app.set_video_frame(slint::Image::from_rgba8(buffer));
                });
                if shown.is_err() {
                    break;
                }
            }
        })
        .context("could not start render thread")
}

fn wire_controls(app: &ui::VideoWindow, mpv: &'static Mpv) {
    app.on_toggle_pause(move || {
        let paused = mpv.get_property::<bool>("pause").unwrap_or(false);
        if let Err(err) = mpv.set_property("pause", !paused) {
            tracing::warn!(?err, "pause toggle failed");
        }
    });
    app.on_seek(move |delta| {
        if let Err(err) = mpv.command("seek", &[&delta.to_string(), "relative"]) {
            tracing::warn!(?err, "seek failed");
        }
    });
}

/// Fit the window into the 854×480 box, keeping the window's aspect ratio.
fn fit(width: u32, height: u32) -> (u32, u32) {
    let (w, h) = (width.max(1), height.max(1));
    if w <= MAX_WIDTH && h <= MAX_HEIGHT {
        return (w, h);
    }
    if u64::from(w) * u64::from(MAX_HEIGHT) >= u64::from(h) * u64::from(MAX_WIDTH) {
        (MAX_WIDTH, (h * MAX_WIDTH / w).max(1))
    } else {
        ((w * MAX_HEIGHT / h).max(1), MAX_HEIGHT)
    }
}

fn pack(width: u32, height: u32) -> u64 {
    (u64::from(width) << 32) | u64::from(height)
}

fn unpack(packed: u64) -> (u32, u32) {
    (
        u32::try_from(packed >> 32).unwrap_or(MAX_WIDTH),
        u32::try_from(packed & 0xFFFF_FFFF).unwrap_or(MAX_HEIGHT),
    )
}

fn clock(seconds: f64) -> String {
    let secs = Duration::try_from_secs_f64(seconds.max(0.0))
        .unwrap_or_default()
        .as_secs();
    format!("{}:{:02}", secs / 60, secs % 60)
}

fn percentile(sorted: &[f64], p: usize) -> f64 {
    sorted
        .get(sorted.len().saturating_sub(1) * p / 100)
        .copied()
        .unwrap_or(0.0)
}

fn report(mpv: &Mpv, backend: &str, options: &Options, stats: &Stats) {
    let first_frame_ms = match (stats.load_started, stats.first_frame) {
        (Some(load), Some(first)) => first.duration_since(load).as_millis(),
        _ => 0,
    };
    let span = match (stats.frames.first(), stats.frames.last()) {
        (Some(a), Some(b)) => b.duration_since(*a).as_secs_f64(),
        _ => 0.0,
    };
    let count = f64::from(u32::try_from(stats.frames.len()).unwrap_or(u32::MAX));
    let fps = if span > 0.0 {
        (count - 1.0) / span
    } else {
        0.0
    };
    let mut render_ms = stats.render_ms.clone();
    render_ms.sort_by(f64::total_cmp);
    let prop_i = |name: &str| mpv.get_property::<i64>(name).unwrap_or(-1);
    let prop_s = |name: &str| mpv.get_property::<String>(name).unwrap_or_default();
    tracing::info!(
        "RESULT backend={backend} hwdec_req={} hwdec_used={} codec={} first_frame_ms={first_frame_ms} \
         video_fps={fps:.1} render_p50_ms={:.2} render_p95_ms={:.2} render_max_ms={:.1} \
         vo_drops={} decoder_drops={}",
        options.hwdec,
        prop_s("hwdec-current"),
        prop_s("video-codec")
            .split_whitespace()
            .next()
            .unwrap_or(""),
        percentile(&render_ms, 50),
        percentile(&render_ms, 95),
        percentile(&render_ms, 100),
        prop_i("frame-drop-count"),
        prop_i("decoder-frame-drop-count"),
    );
}
