//! ⚠️ THROWAWAY spike S3 — video backend B (Windows).
//!
//! mpv renders with its own Direct3D 11 output (`vo=gpu-next`) into a native child window
//! that we place exactly over the video area of the Slint window. Our controls sit below.
//! Works with any Slint renderer: try `SLINT_BACKEND=winit-skia` or `winit-software`.
//!
//! Usage: `s3-video-wid <file> [--hwdec X] [--seconds N] [--auto-resize] [--warp]`
//! (`--warp` = Direct3D's software rasterizer, simulating a PC without a usable GPU).

use std::cell::{Cell, OnceCell};
use std::rc::Rc;
use std::time::{Duration, Instant};

use anyhow::Context as _;
use libmpv2::Mpv;
use slint::{ComponentHandle as _, PhysicalSize, Timer, TimerMode};
use tracing_subscriber::EnvFilter;

mod ui {
    // Generated by Slint; same scoped allowance as kinora_app.
    #![allow(
        clippy::unwrap_used,
        clippy::as_conversions,
        clippy::panic,
        clippy::indexing_slicing,
        clippy::todo, // std-widgets generate `todo!("Components written in Rust can not get embedded yet.")`
        missing_debug_implementations
    )]
    slint::include_modules!();
}

#[derive(Clone)]
struct Options {
    file: String,
    hwdec: String,
    seconds: Option<u64>,
    auto_resize: bool,
    warp: bool,
    /// Extra `name=value` mpv options (`--opt`), e.g. `profile=fast`.
    extra: Vec<(String, String)>,
}

fn main() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")),
        )
        .with_writer(std::io::stderr)
        .try_init()
        .map_err(|err| anyhow::anyhow!(err))?;
    let options = parse_options()?;
    let backend = std::env::var("SLINT_BACKEND").unwrap_or_else(|_| String::from("default"));

    let app = ui::VideoWindow::new().context("could not create window")?;
    app.set_label(format!("{backend}  hwdec={}  warp={}", options.hwdec, options.warp).into());
    app.show().context("could not show window")?;

    // With winit 0.30 the native window only exists once the event loop runs, so the child
    // window and mpv are created on the first timer tick where the HWND is available.
    let player: Rc<OnceCell<Player>> = Rc::default();
    let _setup_timer = start_setup_timer(&app, &player, &options);

    let weak = app.as_weak();
    let player_for_resize = Rc::clone(&player);
    app.on_geometry_changed(move || {
        if let (Some(app), Some(player)) = (weak.upgrade(), player_for_resize.get()) {
            place_child(&app, &player.child);
        }
    });

    // First frame = mpv's estimated frame number becomes ≥ 1 (polled every 5 ms).
    let first_frame_ms = Rc::new(Cell::new(None::<u128>));
    let first_frame_timer = Timer::default();
    {
        let first = Rc::clone(&first_frame_ms);
        let player = Rc::clone(&player);
        first_frame_timer.start(TimerMode::Repeated, Duration::from_millis(5), move || {
            if let Some(player) = player.get()
                && first.get().is_none()
                && player
                    .mpv
                    .get_property::<i64>("estimated-frame-number")
                    .unwrap_or(0)
                    >= 1
            {
                first.set(Some(player.load_started.elapsed().as_millis()));
            }
        });
    }

    wire_controls(&app, &player);
    let position_timer = Timer::default();
    {
        let weak = app.as_weak();
        let player = Rc::clone(&player);
        position_timer.start(TimerMode::Repeated, Duration::from_millis(250), move || {
            if let (Some(app), Some(player)) = (weak.upgrade(), player.get()) {
                let pos = player.mpv.get_property::<f64>("time-pos").unwrap_or(0.0);
                let dur = player.mpv.get_property::<f64>("duration").unwrap_or(0.0);
                app.set_position_text(format!("{} / {}", clock(pos), clock(dur)).into());
                app.set_paused(player.mpv.get_property::<bool>("pause").unwrap_or(false));
            }
        });
    }

    let resize_timer = Timer::default();
    if options.auto_resize {
        let weak = app.as_weak();
        let resize_start = Instant::now();
        resize_timer.start(TimerMode::Repeated, Duration::from_millis(16), move || {
            if let Some(app) = weak.upgrade() {
                let (width, height) = triangle_size(resize_start.elapsed());
                app.window().set_size(PhysicalSize::new(width, height));
            }
        });
    }

    let quit_timer = Timer::default();
    if let Some(seconds) = options.seconds {
        quit_timer.start(TimerMode::SingleShot, Duration::from_secs(seconds), || {
            if let Err(err) = slint::quit_event_loop() {
                tracing::error!(?err, "could not quit event loop");
            }
        });
    }

    slint::run_event_loop_until_quit().context("event loop failed")?;
    if let Some(player) = player.get() {
        report(player.mpv, &backend, &options, first_frame_ms.get());
    }
    Ok(())
}

/// Creates the child window and mpv on the first tick where the native window exists.
fn start_setup_timer(
    app: &ui::VideoWindow,
    player: &Rc<OnceCell<Player>>,
    options: &Options,
) -> Timer {
    let setup_timer = Timer::default();
    {
        let player = Rc::clone(player);
        let weak = app.as_weak();
        let options = options.clone();
        setup_timer.start(TimerMode::Repeated, Duration::from_millis(5), move || {
            if player.get().is_some() {
                return;
            }
            let Some(app) = weak.upgrade() else { return };
            let Ok(parent) = win32::parent_hwnd(&app) else {
                return;
            }; // not created yet
            match Player::start(&app, parent, &options) {
                Ok(started) => {
                    let _ = player.set(started);
                }
                Err(err) => {
                    tracing::error!("player setup failed: {err:#}");
                    if let Err(err) = slint::quit_event_loop() {
                        tracing::error!(?err, "could not quit event loop");
                    }
                }
            }
        });
    }

    setup_timer
}

/// mpv plus the child window it draws into.
struct Player {
    mpv: &'static Mpv,
    child: win32::ChildWindow,
    load_started: Instant,
}

impl Player {
    fn start(
        app: &ui::VideoWindow,
        parent: windows_sys::Win32::Foundation::HWND,
        options: &Options,
    ) -> anyhow::Result<Self> {
        let child = win32::ChildWindow::create(parent)?;
        place_child(app, &child);
        let started = Instant::now();
        let mpv = create_mpv(options, child.id()?)?;
        tracing::info!(ms = started.elapsed().as_millis(), "mpv instance created");
        // Throwaway spike: leak for a 'static borrow (the real wrapper will own it).
        let mpv: &'static Mpv = Box::leak(Box::new(mpv));
        let load_started = Instant::now();
        mpv.command("loadfile", &[&options.file])
            .map_err(|err| anyhow::anyhow!("loadfile: {err:?}"))?;
        Ok(Self {
            mpv,
            child,
            load_started,
        })
    }
}

fn parse_options() -> anyhow::Result<Options> {
    let mut args = std::env::args().skip(1);
    let file = args
        .next()
        .context("usage: s3-video-wid <file> [options]")?;
    let mut options = Options {
        file,
        hwdec: String::from("auto-safe"),
        seconds: None,
        auto_resize: false,
        warp: false,
        extra: Vec::new(),
    };
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--hwdec" => options.hwdec = args.next().context("--hwdec needs a value")?,
            "--seconds" => {
                options.seconds = Some(args.next().context("--seconds needs a value")?.parse()?);
            }
            "--auto-resize" => options.auto_resize = true,
            "--warp" => options.warp = true,
            "--opt" => {
                let pair = args.next().context("--opt needs name=value")?;
                let (name, value) = pair.split_once('=').context("--opt needs name=value")?;
                options.extra.push((name.to_owned(), value.to_owned()));
            }
            other => anyhow::bail!("unknown argument `{other}`"),
        }
    }
    Ok(options)
}

/// Same hardening as S2, but mpv uses its own video output inside our child window.
fn create_mpv(options: &Options, wid: i64) -> anyhow::Result<Mpv> {
    Mpv::with_initializer(|init| {
        init.set_option("wid", wid)?;
        for (name, value) in [
            ("vo", "gpu-next"),
            ("gpu-api", "d3d11"),
            ("hwdec", options.hwdec.as_str()),
            ("config", "no"),
            ("d3d11-warp", if options.warp { "yes" } else { "auto" }),
        ] {
            init.set_option(name, value)?;
        }
        for (name, value) in [
            ("ytdl", "no"),
            ("load-scripts", "no"),
            ("osc", "no"),
            ("input-default-bindings", "no"),
            ("input-vo-keyboard", "no"),
            ("input-cursor-passthrough", "yes"), // clicks on the video go to our window
            ("cursor-autohide", "no"),
            ("terminal", "no"),
            ("keep-open", "yes"),
            ("loop-file", "inf"),
        ] {
            if let Err(err) = init.set_option(name, value) {
                tracing::warn!(name, ?err, "mpv option not accepted");
            }
        }
        for (name, value) in &options.extra {
            init.set_option(name, value.as_str())?;
        }
        Ok(())
    })
    .map_err(|err| anyhow::anyhow!("could not create mpv: {err:?}"))
}

fn place_child(app: &ui::VideoWindow, child: &win32::ChildWindow) {
    child.place(0, 0, app.get_video_width_px(), app.get_video_height_px());
}

fn wire_controls(app: &ui::VideoWindow, player: &Rc<OnceCell<Player>>) {
    let p = Rc::clone(player);
    app.on_toggle_pause(move || {
        if let Some(player) = p.get() {
            let paused = player.mpv.get_property::<bool>("pause").unwrap_or(false);
            if let Err(err) = player.mpv.set_property("pause", !paused) {
                tracing::warn!(?err, "pause toggle failed");
            }
        }
    });
    let p = Rc::clone(player);
    app.on_seek(move |delta| {
        if let Some(player) = p.get()
            && let Err(err) = player
                .mpv
                .command("seek", &[&delta.to_string(), "relative"])
        {
            tracing::warn!(?err, "seek failed");
        }
    });
}

fn clock(seconds: f64) -> String {
    let secs = Duration::try_from_secs_f64(seconds.max(0.0))
        .unwrap_or_default()
        .as_secs();
    format!("{}:{:02}", secs / 60, secs % 60)
}

fn triangle_size(elapsed: Duration) -> (u32, u32) {
    let phase = u32::try_from(elapsed.as_millis() % 2000).unwrap_or(0);
    let t = if phase < 1000 { phase } else { 2000 - phase };
    (800 + t * 800 / 1000, 506 + t * 450 / 1000)
}

fn report(mpv: &Mpv, backend: &str, options: &Options, first_frame_ms: Option<u128>) {
    let prop_i = |name: &str| mpv.get_property::<i64>(name).unwrap_or(-1);
    let prop_f = |name: &str| mpv.get_property::<f64>(name).unwrap_or(-1.0);
    let prop_s = |name: &str| mpv.get_property::<String>(name).unwrap_or_default();
    tracing::info!(
        "RESULT backend={backend} hwdec_req={} hwdec_used={} codec={} first_frame_ms={} \
         vf_fps={:.1} display_fps={:.1} vo_drops={} decoder_drops={} delayed={} mistimed={} \
         auto_resize={} warp={}",
        options.hwdec,
        prop_s("hwdec-current"),
        prop_s("video-codec")
            .split_whitespace()
            .next()
            .unwrap_or(""),
        first_frame_ms.map_or(-1, |ms| i64::try_from(ms).unwrap_or(-1)),
        prop_f("estimated-vf-fps"),
        prop_f("estimated-display-fps"),
        prop_i("frame-drop-count"),
        prop_i("decoder-frame-drop-count"),
        prop_i("vo-delayed-frame-count"),
        prop_i("mistimed-frame-count"),
        options.auto_resize,
        options.warp,
    );
}

/// The only Win32 code in the spike: find our window's HWND and manage a child window.
#[allow(unsafe_code)]
mod win32 {
    use std::ffi::c_void;

    use anyhow::Context as _;
    use raw_window_handle::{HasWindowHandle as _, RawWindowHandle};
    use slint::ComponentHandle as _;
    use windows_sys::Win32::Foundation::HWND;
    use windows_sys::Win32::System::LibraryLoader::GetModuleHandleW;
    use windows_sys::Win32::UI::WindowsAndMessaging::{
        CreateWindowExW, DestroyWindow, GWL_STYLE, GetWindowLongPtrW, SWP_NOACTIVATE, SWP_NOZORDER,
        SetWindowLongPtrW, SetWindowPos, WS_CHILD, WS_CLIPCHILDREN, WS_CLIPSIBLINGS, WS_VISIBLE,
    };

    /// The top-level HWND behind the Slint window (available once the window is shown).
    pub fn parent_hwnd(app: &super::ui::VideoWindow) -> anyhow::Result<HWND> {
        let handle = app.window().window_handle();
        let raw = handle
            .window_handle()
            .map_err(|err| anyhow::anyhow!("no native window handle: {err}"))?
            .as_raw();
        let RawWindowHandle::Win32(win32) = raw else {
            anyhow::bail!("not a Win32 window");
        };
        let address = usize::try_from(win32.hwnd.get()).context("negative HWND")?;
        Ok(std::ptr::with_exposed_provenance_mut::<c_void>(address))
    }

    #[derive(Debug)]
    pub struct ChildWindow(HWND);

    impl ChildWindow {
        pub fn create(parent: HWND) -> anyhow::Result<Self> {
            let class: Vec<u16> = "STATIC\0".encode_utf16().collect();
            let clip_children = isize::try_from(WS_CLIPCHILDREN).unwrap_or(0);
            // SAFETY: `parent` is the live top-level window created by Slint on this thread;
            // `class` is a NUL-terminated UTF-16 string that outlives the call; all other
            // pointers are null, which CreateWindowExW documents as allowed.
            let hwnd = unsafe {
                // Stop the parent from painting over its child windows.
                let style = GetWindowLongPtrW(parent, GWL_STYLE);
                SetWindowLongPtrW(parent, GWL_STYLE, style | clip_children);
                CreateWindowExW(
                    0,
                    class.as_ptr(),
                    std::ptr::null(),
                    WS_CHILD | WS_VISIBLE | WS_CLIPSIBLINGS,
                    0,
                    0,
                    1,
                    1,
                    parent,
                    std::ptr::null_mut(),
                    GetModuleHandleW(std::ptr::null()),
                    std::ptr::null(),
                )
            };
            anyhow::ensure!(!hwnd.is_null(), "CreateWindowExW failed");
            Ok(Self(hwnd))
        }

        pub fn place(&self, x: i32, y: i32, width: i32, height: i32) {
            // SAFETY: `self.0` is a child window we created and have not destroyed.
            unsafe {
                SetWindowPos(
                    self.0,
                    std::ptr::null_mut(),
                    x,
                    y,
                    width,
                    height,
                    SWP_NOZORDER | SWP_NOACTIVATE,
                );
            }
        }

        /// The HWND as the integer mpv's `wid` option expects.
        pub fn id(&self) -> anyhow::Result<i64> {
            Ok(i64::try_from(self.0.expose_provenance())?)
        }
    }

    impl Drop for ChildWindow {
        fn drop(&mut self) {
            // SAFETY: we created this window on this thread and destroy it exactly once.
            unsafe {
                DestroyWindow(self.0);
            }
        }
    }
}
